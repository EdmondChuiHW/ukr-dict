/** Machine-readable artifacts: JSONL dumps + type definitions + README. */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { Entry } from '@ukdict/shared';
import type { IgnoredEntry } from '../contracts.ts';
import { writeJsonl } from './jsonl.ts';

const IGNORED_TYPE = `
// ───────────── machine/ignored-entries.jsonl (one IgnoredEntry per line) ─────────────

export interface IgnoredEntry {
  word: string;
  /** Raw kaikki POS. */
  kaikkiPos: string;
  pos: PartOfSpeech;
  reason: 'inflected-form-only' | 'no-senses';
  /** Base forms this entry is an inflection of, with the grammatical tags of the inflection. */
  formOf: { word: string; tags: string[] }[];
  glosses: string[];
  /** 1-based line in kaikki.org-dictionary-Ukrainian.jsonl. */
  line: number;
  url: string;
  /** in-paradigm: the form already appears in the lemma's table; added-as-extra-form: attached to the lemma's extraForms; lemma-missing: no lemma entry found. */
  resolution?: 'in-paradigm' | 'added-as-extra-form' | 'lemma-missing';
}
`;

function readme(counts: { entries: number; created: number; ignored: number }): string {
  return `# Machine-readable artifacts

Generated by the ukdict pipeline (\`pnpm pipeline\`). All files are UTF-8.

| file | content |
|---|---|
| \`entries.jsonl\` | ${counts.entries} dictionary entries, one JSON \`Entry\` per line, sorted by \`id\` (= frequency order: lower id = more frequent). |
| \`created-entries.jsonl\` | ${counts.created} entries synthesized from English Wiktionary translation tables (subset of entries.jsonl with \`created\` set). |
| \`ignored-entries.jsonl\` | ${counts.ignored} kaikki entries that were not turned into dictionary entries (inflected forms only / no senses), with the reason, their base form(s) and how they were resolved (\`resolution\`). |
| \`schema.d.ts\` | TypeScript definitions of \`Entry\` and every nested type (copy of packages/shared/src/types.ts) plus \`IgnoredEntry\`. |

Notes
- \`word\` is the headword without stress marks; \`heads\` holds stressed spellings (combining U+0301).
- \`key\` = search key (lower-case, stress-free, normalized apostrophes); see packages/shared/src/normalize.ts.
- \`paradigm.forms\` maps slot keys (closed vocabulary, packages/shared/src/paradigm.ts) to stressed forms.
- \`id\` values are only stable within one build; \`slug\` (\`word~pos[~n]\`) is stable while the source data is.
- Licensing: Wiktionary-derived content is CC BY-SA 4.0 / GFDL; see the attributions in web/manifest.json.
`;
}

export interface MachineEmitResult {
  files: { path: string; bytes: number }[];
}

export async function emitMachineArtifacts(
  entries: readonly Entry[],
  ignored: readonly IgnoredEntry[],
  opts: { outDir: string; schemaSource?: string },
): Promise<MachineEmitResult> {
  const dir = opts.outDir;
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
  const created = entries.filter((e) => e.created);
  const files: { path: string; bytes: number }[] = [];
  const [a, b, c] = await Promise.all([
    writeJsonl(join(dir, 'entries.jsonl'), entries),
    writeJsonl(join(dir, 'ignored-entries.jsonl'), ignored),
    writeJsonl(join(dir, 'created-entries.jsonl'), created),
  ]);
  files.push({ path: 'entries.jsonl', bytes: a }, { path: 'ignored-entries.jsonl', bytes: b }, { path: 'created-entries.jsonl', bytes: c });

  const schemaPath = opts.schemaSource ?? new URL('../../../shared/src/types.ts', import.meta.url);
  const types = await readFile(schemaPath, 'utf8');
  const schema = `/* Generated by the ukdict pipeline: copy of packages/shared/src/types.ts + IgnoredEntry. */\n\n${types}${IGNORED_TYPE}`;
  await writeFile(join(dir, 'schema.d.ts'), schema);
  files.push({ path: 'schema.d.ts', bytes: Buffer.byteLength(schema) });
  const md = readme({ entries: entries.length, created: created.length, ignored: ignored.length });
  await writeFile(join(dir, 'README.md'), md);
  files.push({ path: 'README.md', bytes: Buffer.byteLength(md) });
  return { files };
}
